"""Course report Appendix E table: Bonferroni and Benjamini-Hochberg decisions on the 10 Q1 bin p-values.

Why: the owner asked for each correction as an appendix (2026-11-18). Numbers come from the saved run, not by hand.
Reads saved outputs only: runs/142082_mvp1_full_v1r3/q1_bins.csv. Writes papers/course_report_mvp1/q1_corrections.tex.
"""
from pathlib import Path

import pandas as pd

__all__ = ["rows"]

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "runs" / "142082_mvp1_full_v1r3" / "q1_bins.csv"
OUT = ROOT / "papers" / "course_report_mvp1" / "q1_corrections.tex"
ALPHA, M = 0.05, 10


def fmt_p(p: float) -> str:
    return f"{p:.2g}" if p >= 1e-3 else f"{p:.1e}".replace("e-0", r"\times10^{-").replace("e-", r"\times10^{-") + "}"


def rows(b: pd.DataFrame) -> list[str]:
    b = b.sort_values("binom_p").reset_index(drop=True)
    out = []
    for i, r in b.iterrows():
        rank = i + 1
        bonf = r["binom_p"] < ALPHA / M
        out.append(f"{rank} & {int(r['bin'])} & ${fmt_p(r['binom_p'])}$ & {'yes' if bonf else 'no'} & "
                   f"{rank * ALPHA / M:.3f} & {'yes' if bool(r['reject_bh']) else 'no'} \\\\")
    return out


def main() -> None:
    b = pd.read_csv(SRC)
    body = "\n\\midrule\n".join(rows(b))
    OUT.write_text("% Generated by code/make_report_q1_corrections.py from " + SRC.relative_to(ROOT).as_posix() + "\n"
                   "\\begin{tabular}{@{}rrrcrc@{}}\n\\toprule\n"
                   "Rank & Bin & $p$ & Bonferroni ($p<0.005$) & BH cut (rank $\\times$ 0.005) & BH \\\\\n\\midrule\n"
                   + body + "\n\\bottomrule\n\\end{tabular}\n")
    print(OUT)


if __name__ == "__main__":
    main()
